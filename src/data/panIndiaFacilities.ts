/**
 * Deterministic generator to guarantee that ANY selected State/UT and District
 * has facilities across all 4 public healthcare tiers: Sub-Centre, PHC, Rural Hospital, and District Hospital.
 */
export function getPanIndiaFacilitiesForDistrict(
  stateName: string,
  districtName: string
): Facility[] {
  // Check if we have manually seeded facilities first
  const manualMatches = PRIMARY_PAN_INDIA_FACILITIES.filter(
    (f) =>
      f.state.toLowerCase() === stateName.toLowerCase() &&
      f.district.toLowerCase() === districtName.toLowerCase()
  );

  if (manualMatches.length >= 4) {
    return manualMatches;
  }

  const stateObj = INDIAN_STATES_AND_UTS.find(
    (s) => s.name.toLowerCase() === stateName.toLowerCase()
  );
  const stateCode = stateObj?.code || 'IN';
  const districtObj = stateObj?.districts.find(
    (d) => d.name.toLowerCase() === districtName.toLowerCase()
  );
  const basePincode = districtObj?.pincode || '110001';
  const pinNum = parseInt(basePincode, 10) || 110001;

  const tiers: Array<{
    tier: FacilityTier;
    suffix: string;
    beds: number;
    hasLab: boolean;
    hasPharmacy: boolean;
    hasEmergency: boolean;
    idPrefix: string;
  }> = [
    {
      tier: 'sub_centre',
      suffix: 'Health Sub-Centre (Ayushman Arogya Mandir)',
      beds: 2,
      hasLab: false,
      hasPharmacy: true,
      hasEmergency: false,
      idPrefix: 'sc',
    },
    {
      tier: 'phc',
      suffix: 'Primary Health Centre',
      beds: 10,
      hasLab: true,
      hasPharmacy: true,
      hasEmergency: true,
      idPrefix: 'phc',
    },
    {
      tier: 'rural_hospital',
      suffix: 'Rural Community Hospital (CHC)',
      beds: 45,
      hasLab: true,
      hasPharmacy: true,
      hasEmergency: true,
      idPrefix: 'rh',
    },
    {
      tier: 'district_hospital',
      suffix: 'District Civil Headquarters Hospital',
      beds: 350,
      hasLab: true,
      hasPharmacy: true,
      hasEmergency: true,
      idPrefix: 'dh',
    },
  ];

  const generated: Facility[] = tiers.map((tInfo, idx) => {
    // If we already have a seeded match for this tier, use that one
    const existing = manualMatches.find((m) => m.tier === tInfo.tier);
    if (existing) return existing;

    const safeSlug = `${stateCode.toLowerCase()}_${districtName.toLowerCase().replace(/[^a-z0-9]/g, '_')}_${tInfo.idPrefix}`;
    return {
      id: `fac_${safeSlug}`,
      name: `${districtName} ${tInfo.suffix}`,
      tier: tInfo.tier,
      district: districtName,
      state: stateName,
      stateCode,
      pincode: String(pinNum + idx * 2),
      latitude: 20.5937 + (idx * 0.05),
      longitude: 78.9629 + (idx * 0.05),
      beds: tInfo.beds,
      hasLab: tInfo.hasLab,
      hasPharmacy: tInfo.hasPharmacy,
      hasEmergency: tInfo.hasEmergency,
      contactNumber: `+91 ${stateCode === 'DL' ? '11' : '674'} 2800 ${idx}00`,
      headOfFacility:
        tInfo.tier === 'sub_centre'
          ? 'Sister Priya Nair (CHO)'
          : tInfo.tier === 'phc'
          ? 'Dr. Vivek Sengupta (MO)'
          : tInfo.tier === 'rural_hospital'
          ? 'Dr. Ramesh Chandra (Superintendent)'
          : 'Dr. Aditi Sharma (Chief Medical Officer)',
      connectivityStatus: idx === 0 ? 'degraded' : 'connected',
    };
  });

  return generated;
}

/**
 * Combined Registry of all facilities (pre-seeded + dynamic pool)
 */
export function getAllPanIndiaFacilities(): Facility[] {
  const result: Facility[] = [...PRIMARY_PAN_INDIA_FACILITIES];
  const existingIds = new Set(result.map((f) => f.id));

  // Generate for all districts across all 28 states + 8 UTs so that search by PIN or district works across entire India
  INDIAN_STATES_AND_UTS.forEach((state) => {
    state.districts.forEach((dist) => {
      const distFacilities = getPanIndiaFacilitiesForDistrict(state.name, dist.name);
      distFacilities.forEach((fac) => {
        if (!existingIds.has(fac.id)) {
          existingIds.add(fac.id);
          result.push(fac);
        }
      });
    });
  });

  return result;
}

export function getStateCodeByName(stateName: string): string {
  const found = INDIAN_STATES_AND_UTS.find(
    (s) => s.name.toLowerCase() === stateName.toLowerCase()
  );
  return found?.code || stateName.slice(0, 2).toUpperCase();
}
